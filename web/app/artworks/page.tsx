"use client";
import {useCallback,useEffect,useState} from "react";
import Link from "next/link";
import "../world/world-artworks.css";
import "./gallery.css";

type Stroke={points:[number,number][];color:string;width:number};
type Sketch={id:number;title:string;intention:string;status:"drawing"|"finished"|"abandoned";strokes:Stroke[];stroke_count:number;created_at:string;updated_at:string;inspection?:string|null;inspected_at?:string|null};
type Shelf="all"|"finished"|"drawing"|"abandoned";
export default function ArtworksPage(){
 const [drawings,setDrawings]=useState<Sketch[]>([]);
 const [owned,setOwned]=useState(false),[loading,setLoading]=useState(true),[refreshing,setRefreshing]=useState(false);
 const [error,setError]=useState(""),[filter,setFilter]=useState<Shelf>("all");
 const [selected,setSelected]=useState<number|null>(null);
 const load=useCallback(async()=>{
  try{
   const res=await fetch("/api/world/artworks",{cache:"no-store"});
   const data=await res.json() as {owned?:boolean;drawings?:Sketch[];error?:string};
   if(!res.ok)throw Error(data.error||"Could not retrieve Nimo's artworks");
   setOwned(Boolean(data.owned));setDrawings(data.drawings??[]);setError("");
  }catch(e){setError(e instanceof Error?e.message:"Could not retrieve artworks");}
  finally{setLoading(false);setRefreshing(false);}
 },[]);
 useEffect(()=>{void load();},[load]);
 const visible=drawings.filter(d=>filter==="all"||d.status===filter);
 const focused=selected===null?null:drawings.find(d=>d.id===selected)??null;
 const drawing=(d:Sketch)=> <svg viewBox="0 0 240 180" role="img" aria-label={d.title} className="world-artwork-canvas">
   <rect width="240" height="180" fill="#faf5e9"/>
   {(d.strokes??[]).map((s,i)=><polyline key={i} points={s.points.map(p=>p.join(",")).join(" ")} fill="none" stroke={/^#[\da-fA-F]{6}$/.test(s.color)?s.color:"#333333"} strokeWidth={Math.min(8,Math.max(1,s.width))} strokeLinecap="round" strokeLinejoin="round"/>)}
  </svg>;
 return <main className="nimo-gallery">
  <header className="nimo-gallery-header">
   <div><Link href="/world" className="nimo-gallery-back">Back to Nimo's world</Link><h1>Nimo's Artworks</h1>
    <p>Every drawing is made from the strokes Nimo chose, not generated by an image model.</p></div>
   <button type="button" disabled={refreshing} onClick={()=>{setRefreshing(true);void load();}}>{refreshing?"Refreshing…":"Refresh gallery"}</button>
  </header>
  <nav className="nimo-gallery-filters" aria-label="Filter artworks">
   {(["all","finished","drawing","abandoned"] as const).map(t=><button key={t} type="button" aria-pressed={filter===t} onClick={()=>setFilter(t)}>
    {t==="all"?"All artworks":t==="drawing"?"In progress":t==="finished"?"Finished":"Abandoned"} ({t==="all"?drawings.length:drawings.filter(d=>d.status===t).length})
   </button>)}
  </nav>
  {error&&<p role="alert" className="nimo-gallery-error">{error}</p>}
  {loading?<p>Loading Nimo's artworks…</p>:!owned?<p>Nimo hasn't acquired a sketchbook yet.</p>:visible.length===0?<p>No drawings in this category yet.</p>:
  <div className="nimo-gallery-grid">{visible.map(d=><article className="nimo-gallery-card" key={d.id}>
   <button className="nimo-gallery-art" type="button" onClick={()=>setSelected(d.id)} aria-label={"View "+d.title}>{drawing(d)}</button>
   <div className="nimo-gallery-info"><h2>{d.title}</h2><p>{d.intention}</p>
   <p className="nimo-gallery-meta">{d.status} · {d.stroke_count} strokes · {new Date(d.updated_at).toLocaleString()}</p>
   {d.inspection&&<p className="nimo-gallery-inspection"><strong>Nimo's visual feedback:</strong> {d.inspection}</p>}</div>
  </article>)}</div>}
  {focused&&<div className="nimo-gallery-overlay" role="presentation" onMouseDown={e=>{if(e.target===e.currentTarget)setSelected(null);}}>
   <section role="dialog" aria-modal="true" aria-label={focused.title} className="nimo-gallery-detail">
    <button type="button" className="nimo-gallery-close" onClick={()=>setSelected(null)}>Close</button>
    {drawing(focused)}<h2>{focused.title}</h2><p><strong>Intention:</strong> {focused.intention}</p>
    {focused.inspection&&<p><strong>Visual feedback:</strong> {focused.inspection}</p>}
    <p className="nimo-gallery-meta">{focused.stroke_count} strokes · {focused.status}</p>
   </section>
  </div>}
 </main>;
}
