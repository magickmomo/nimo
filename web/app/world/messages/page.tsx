"use client";
import { useCallback,useEffect,useState } from "react";
import "../world.css";
type Message={id:number;created_at:string;kind:string;content:string;action:string|null};
export default function WorldMessages() {
  const [messages,setMessages]=useState<Message[]>([]);
  const [authenticated,setAuthenticated]=useState<boolean|null>(null);
  const [draft,setDraft]=useState("");
  const [sending,setSending]=useState(false);
  const [error,setError]=useState("");
  const load=useCallback(async()=>{
    try {
      const response=await fetch("/api/world/messages",{cache:"no-store"});
      if(response.status===401){setAuthenticated(false);return;}
      const data=await response.json() as {messages?:Message[];error?:string};
      if(!response.ok)throw Error(data.error||"Conversation unavailable");
      setMessages(data.messages||[]);
      setAuthenticated(true);setError("");
    }catch(err){setError(err instanceof Error?err.message:"Conversation unavailable");}
  },[]);
  useEffect(()=>{
    void load();
    const timer=window.setInterval(()=>{if(document.visibilityState==="visible")void load();},15000);
    return()=>window.clearInterval(timer);
  },[load]);
  async function send(e:React.FormEvent) {
    e.preventDefault();if(!draft.trim()||sending)return;
    setSending(true);setError("");
    try{
      const response=await fetch("/api/world/message",{
        method:"POST",headers:{"Content-Type":"application/json"},
        body:JSON.stringify({message:draft.trim()}),
      });
      const data=await response.json() as {error?:string};
      if(!response.ok)throw Error(data.error||"Message failed");
      setDraft("");await load();
    }catch(err){setError(err instanceof Error?err.message:"Unable to send");}
    finally{setSending(false);}
  }
  return <main className="world-page world-messages">
    <div className="world-topbar">
      <a href="/world">World</a>
      <a href="/world/settings">Settings</a>
    </div>
    <h1>Messages</h1>
    <p className="meta">Your messages, Nimo's replies and his capability requests. Nimo reads messages from this same persistent conversation in his normal decision context.</p>
    {error&&<p className="world-warning" role="alert">{error}</p>}
    {authenticated===false ? <section className="world-card">
      <p>Sign in once using your existing owner token under World Settings. You won't need to enter it when messaging Nimo.</p>
      <a href="/world/settings">Sign in under World Settings</a>
    </section> : <>
      <section className="world-card world-message-thread" aria-label="Conversation history">
        {messages.length===0?<p className="meta">{authenticated===null?"Loading conversation…":"No messages yet."}</p>:
        messages.map(item=>{
          const isYou=item.kind==="visitor",isRequest=item.action==="REQUEST";
          return <article key={item.id} className={"world-message "+(isYou?"from-owner":isRequest?"is-request":"from-nimo")}>
            <div className="world-message-meta">
              <strong>{isYou?"You":isRequest?"Nimo · Request":"Nimo"}</strong>
              <time dateTime={item.created_at}>{new Date(item.created_at).toLocaleString()}</time>
            </div>
            <p>{item.content}</p>
          </article>;
        })}
      </section>
      <form className="world-card world-message-compose" onSubmit={send}>
        <label htmlFor="nimo-message">Message Nimo</label>
        <textarea id="nimo-message" rows={3} maxLength={1000} value={draft} onChange={e=>setDraft(e.target.value)} placeholder="Write a message…" required />
        <div className="world-message-actions">
          <button type="button" onClick={()=>void load()}>Refresh</button>
          <button disabled={!draft.trim()||sending||authenticated!==true}>{sending?"Sending…":"Send message"}</button>
        </div>
        <p className="meta">Replies are generated by Nimo's next autonomous decision, not instantly.</p>
      </form>
    </>}
  </main>;
}
